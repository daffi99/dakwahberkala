// scripts/export-supabase-to-neon.mjs
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import { createClient } from '@supabase/supabase-js'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)
const rootDir = path.resolve(__dirname, '..')

// Simple .env.local reader
function loadEnvLocal() {
  const envPath = path.join(rootDir, '.env.local')
  if (!fs.existsSync(envPath)) return

  const content = fs.readFileSync(envPath, 'utf8')
  for (const line of content.split('\n')) {
    const trimmed = line.trim()
    if (!trimmed || trimmed.startsWith('#')) continue
    const eqIdx = trimmed.indexOf('=')
    if (eqIdx !== -1) {
      const key = trimmed.slice(0, eqIdx).trim()
      let val = trimmed.slice(eqIdx + 1).trim()
      if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
        val = val.slice(1, -1)
      }
      if (!process.env[key]) {
        process.env[key] = val
      }
    }
  }
}

loadEnvLocal()

const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL || 'https://pzovdnisolhwlzznyzfh.supabase.co'
const supabaseKey = process.env.SUPABASE_SERVICE_ROLE_KEY || process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY

function escapeSqlString(str) {
  if (str === null || str === undefined) return 'NULL'
  return "'" + String(str).replace(/'/g, "''") + "'"
}

function escapeJsonb(obj) {
  if (obj === null || obj === undefined) return "'[]'::jsonb"
  const str = typeof obj === 'string' ? obj : JSON.stringify(obj)
  return "'" + str.replace(/'/g, "''") + "'::jsonb"
}

async function exportData() {
  console.log('📡 Fetching all articles from Supabase...')
  const supabase = createClient(supabaseUrl, supabaseKey)

  const { data, error } = await supabase
    .from('articles')
    .select('*')
    .order('id', { ascending: true })

  if (error) {
    console.error('❌ Error fetching from Supabase:', error)
    process.exit(1)
  }

  console.log(`✅ Successfully retrieved ${data.length} articles from Supabase!`)

  // Construct SQL schema and inserts
  let sql = `-- ============================================================
-- SQL Export from Supabase for Neon Postgres
-- Generated: ${new Date().toISOString()}
-- Total Articles: ${data.length}
-- ============================================================

-- 1. Create table structure in Neon (if not exists)
CREATE TABLE IF NOT EXISTS public.articles (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug text UNIQUE NOT NULL,
  title text NOT NULL,
  category text NOT NULL,
  badge text NOT NULL,
  badge_style text NOT NULL DEFAULT 'badge--gray',
  tldr text NOT NULL,
  cover_gradient text NOT NULL DEFAULT 'linear-gradient(135deg, #0B4F49 0%, #0F766E 50%, #1a8a81 100%)',
  cover_emoji text NOT NULL DEFAULT '🌙',
  card_bg text NOT NULL DEFAULT '#DFF0ED',
  sources integer NOT NULL DEFAULT 0,
  updated_at text NOT NULL,
  kesimpulan jsonb NOT NULL DEFAULT '[]'::jsonb,
  pendapat jsonb NOT NULL DEFAULT '[]'::jsonb,
  dalil jsonb NOT NULL DEFAULT '[]'::jsonb,
  sikap_praktis jsonb NOT NULL DEFAULT '[]'::jsonb,
  sumber jsonb NOT NULL DEFAULT '[]'::jsonb,
  created_at timestamp with time zone NOT NULL DEFAULT now()
);

-- 2. Insert all articles exported from Supabase
`

  for (const item of data) {
    const fields = [
      'slug', 'title', 'category', 'badge', 'badge_style', 'tldr',
      'cover_gradient', 'cover_emoji', 'card_bg', 'sources', 'updated_at',
      'kesimpulan', 'pendapat', 'dalil', 'sikap_praktis', 'sumber'
    ]

    const values = [
      escapeSqlString(item.slug),
      escapeSqlString(item.title),
      escapeSqlString(item.category),
      escapeSqlString(item.badge),
      escapeSqlString(item.badge_style || 'badge--gray'),
      escapeSqlString(item.tldr),
      escapeSqlString(item.cover_gradient || 'linear-gradient(135deg, #0B4F49 0%, #0F766E 50%, #1a8a81 100%)'),
      escapeSqlString(item.cover_emoji || '🌙'),
      escapeSqlString(item.card_bg || '#DFF0ED'),
      parseInt(item.sources, 10) || 0,
      escapeSqlString(item.updated_at),
      escapeJsonb(item.kesimpulan),
      escapeJsonb(item.pendapat),
      escapeJsonb(item.dalil),
      escapeJsonb(item.sikap_praktis),
      escapeJsonb(item.sumber)
    ]

    sql += `INSERT INTO public.articles (${fields.join(', ')})
VALUES (
  ${values.join(',\n  ')}
)
ON CONFLICT (slug) DO UPDATE SET
  title = EXCLUDED.title,
  category = EXCLUDED.category,
  badge = EXCLUDED.badge,
  badge_style = EXCLUDED.badge_style,
  tldr = EXCLUDED.tldr,
  cover_gradient = EXCLUDED.cover_gradient,
  cover_emoji = EXCLUDED.cover_emoji,
  card_bg = EXCLUDED.card_bg,
  sources = EXCLUDED.sources,
  updated_at = EXCLUDED.updated_at,
  kesimpulan = EXCLUDED.kesimpulan,
  pendapat = EXCLUDED.pendapat,
  dalil = EXCLUDED.dalil,
  sikap_praktis = EXCLUDED.sikap_praktis,
  sumber = EXCLUDED.sumber;

`
  }

  // Save to supabase_export_for_neon.sql
  const exportPath = path.join(rootDir, 'supabase_export_for_neon.sql')
  fs.writeFileSync(exportPath, sql, 'utf8')
  console.log(`📁 Saved export to: ${exportPath}`)

  // Also update neon_schema.sql so npm run migrate:neon uses the full 7 articles
  const neonSchemaPath = path.join(rootDir, 'neon_schema.sql')
  fs.writeFileSync(neonSchemaPath, sql, 'utf8')
  console.log(`📁 Updated ${neonSchemaPath}`)

  // Also update src/lib/articles.js so fallback has the full 7 real articles
  const mappedArticles = data.map(item => ({
    slug: item.slug,
    title: item.title,
    category: item.category,
    badge: item.badge,
    badgeStyle: item.badge_style || 'badge--gray',
    tldr: item.tldr,
    coverGradient: item.cover_gradient || 'linear-gradient(135deg, #0B4F49 0%, #0F766E 50%, #1a8a81 100%)',
    coverEmoji: item.cover_emoji || '🌙',
    cardBg: item.card_bg || '#DFF0ED',
    sources: parseInt(item.sources, 10) || 0,
    updatedAt: item.updated_at,
    kesimpulan: item.kesimpulan || [],
    pendapat: item.pendapat || [],
    dalil: item.dalil || [],
    sikapPraktis: item.sikap_praktis || [],
    sumber: item.sumber || []
  }))

  const articlesJsPath = path.join(rootDir, 'src/lib/articles.js')
  const articlesJsContent = `// src/lib/articles.js
// Static article data — fallback data exported from Supabase

export const articles = ${JSON.stringify(mappedArticles, null, 2)}

export function getArticleBySlug(slug) {
  return articles.find((a) => a.slug === slug) ?? null
}

export function getAllSlugs() {
  return articles.map((a) => ({ slug: a.slug }))
}
`
  fs.writeFileSync(articlesJsPath, articlesJsContent, 'utf8')
  console.log(`📁 Updated ${articlesJsPath}`)

  console.log('\n🎉 Export complete! All articles from Supabase are now exported and ready for Neon.')
}

exportData()
